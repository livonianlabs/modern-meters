// Sizes the gadget: a pre-rendered rounded panel (img/bg_<w>_<h>.png) on g:background gives the
// corners and border, and opaque divs of the panel color cover the interior. Text must sit on
// opaque HTML, otherwise the Sidebar blends its anti-aliasing with the magenta transparency key.
// Height is rounded up to the 10px steps the panels are generated in.
function paintFrame(w, h) {
    h = clamp(Math.ceil(h / 10) * 10, BG_MIN_H, BG_MAX_H);
    document.body.style.width = w + "px";
    document.body.style.height = h + "px";

    // Glass leaves a wider rim of the image uncovered for its glowing border
    var panel = $("panel"), r = THEME.glass ? 12 : 10, inset = THEME.glass ? 4 : 1;
    panel.innerHTML = "";
    var a = rect(panel, inset, r, w - 2 * inset, h - 2 * r, THEME.panel);
    var b = rect(panel, r, inset, w - 2 * r, h - 2 * inset, THEME.panel);
    if (THEME.glass) {
        // Same vertical gradient as the image: each piece gets the colors at its own top and bottom
        var at = function (y) { return mix(THEME.panelTop, THEME.panelBottom, y / h); };
        gradient(a, at(r), at(h - r));
        gradient(b, at(inset), at(h - inset));
        // Gloss over the top, kept on the opaque pieces (over the bare corners it would blend
        // with the Sidebar's transparency color)
        var gloss = function (y) { return Math.round(clamp(1 - (y - inset) / 70, 0, 1) * 22); };
        var alpha = function (y) { var v = gloss(y); return "#" + (v < 16 ? "0" : "") + v.toString(16) + "FFFFFF"; };
        gradient(box(panel, r, inset, w - 2 * r, r - inset), alpha(inset), alpha(r));
        gradient(box(panel, inset, r, w - 2 * inset, 70 + inset - r), alpha(r), alpha(70 + inset));
    }

    if (!IS_GADGET) {
        // Preview outside the Sidebar (e.g. mshta)
        document.body.style.backgroundColor = THEME.panel;
        try {
            var k = (screen.deviceXDPI || 96) / 96;
            document.body.scroll = "no";
            window.moveTo(0, 0);
            window.resizeTo(Math.round((w + 20) * k), Math.round((h + 50) * k));
        } catch (e) { }
        return;
    }
    var bg = $("bg");
    bg.src = "img/" + (THEME.glass ? "glass_" : "bg_") + w + "_" + h + ".png";
    bg.style.width = w + "px";
    bg.style.height = h + "px";
}

// Turns a label into a clickable hint, or back into plain text (action null). action is a web
