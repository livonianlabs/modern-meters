// ---- horizontal bar -------------------------------------------------------

function Bar(parent, x, y, w, h) {
    this.w = w;
    this.track = rect(parent, x, y, w, h, THEME.track);
    this.fill = rect(this.track, 0, 0, 0, h, THEME.track);
    this.px = 0;
    this.color = null;
}

Bar.prototype.set = function (pct, color) {
    var px = pct == null ? 0 : Math.round(this.w * clamp(pct, 0, 100) / 100);
    if (pct > 0 && px < 1) px = 1;
    if (px != this.px) { this.fill.style.width = px + "px"; this.px = px; }
    if (color != this.color) {
        this.fill.style.backgroundColor = color;
        if (THEME.glass) gradient(this.fill, mix(THEME.track, color, 0.45), color, true);
        this.color = color;
    }
};

// Legacy IE gradient filter (the Sidebar's MSHTML has no CSS gradients); colors are #rrggbb or
// #aarrggbb
function gradient(el, from, to, horizontal) {
    var argb = function (c) { return "#" + (c.length == 7 ? "FF" : "") + c.substr(1); };
    el.style.filter = "progid:DXImageTransform.Microsoft.gradient(startColorstr='" + argb(from) +
        "',endColorstr='" + argb(to) + "',GradientType=" + (horizontal ? 1 : 0) + ")";
}

// ---- history graph --------------------------------------------------------

// Mixes two #rrggbb colors; t=0 gives a, t=1 gives b
function mix(a, b, t) {
    var out = "#";
    for (var i = 1; i < 7; i += 2) {
        var v = Math.round(parseInt(a.substr(i, 2), 16) * (1 - t) + parseInt(b.substr(i, 2), 16) * t);
        out += (v < 16 ? "0" : "") + v.toString(16);
    }
    return out;
}

// Built from plain divs (one 2px column per sample) because the Sidebar doesn't scale VML
// with the screen DPI. series: [{color, area}], values 0..100, newest sample on the right.
// An area series is a filled column with a bright cap; a line series is the cap only.
// noGrid: no quarter lines (sparklines).
function Graph(parent, x, y, w, h, series, noGrid) {
    this.h = h;
    this.n = Math.floor(w / 2);
    this.series = series;
    this.data = [];
    this.cols = [];

    var frame = rect(parent, x, y, w, h, THEME.plot);
    if (!noGrid) for (var i = 1; i < 4; i++) rect(frame, 0, Math.round(h * i / 4), w, 1, THEME.grid);

    var x0 = w - this.n * 2;
    for (var s = 0; s < series.length; s++) {
        var hist = [], cols = [], c = series[s].color, dim = mix(THEME.plot, c, 0.3);
        for (var k = 0; k < this.n; k++) {
            hist.push(0);
            var fill = series[s].area ? rect(frame, x0 + k * 2, h, 2, 0, dim) : null;
            // Glass: the area fades from a bright top to the plot background
            if (fill && THEME.glass) gradient(fill, mix(THEME.plot, c, 0.55), mix(THEME.plot, c, 0.1));
            cols.push({ fill: fill, cap: rect(frame, x0 + k * 2, h - 2, 2, 2, c), v: -1 });
        }
        this.data.push(hist);
        this.cols.push(cols);
    }
}

Graph.prototype.push = function (values) {
    for (var s = 0; s < this.series.length; s++) {
        this.data[s].shift();
        this.data[s].push(values[s] == null ? 0 : clamp(values[s], 0, 100));
    }
    this.draw();
};

// Replaces the whole history (one array per series, oldest first), e.g. after a rescale
Graph.prototype.load = function (values) {
    for (var s = 0; s < this.series.length; s++) {
        var src = values[s], off = src.length - this.n;
        for (var i = 0; i < this.n; i++) {
            var v = src[i + off];
            this.data[s][i] = v == null ? 0 : clamp(v, 0, 100);
        }
    }
    this.draw();
};

Graph.prototype.draw = function () {
    for (var s = 0; s < this.series.length; s++) {
        var hist = this.data[s], cols = this.cols[s];
        var prev = null;
        for (var i = 0; i < this.n; i++) {
            var px = Math.round(hist[i] * (this.h - 2) / 100), col = cols[i];
            // The cap spans from the previous sample to this one so the line stays continuous
            var lo = prev == null ? px : Math.min(px, prev), hi = prev == null ? px : Math.max(px, prev);
            prev = px;
            var key = px * 1000 + lo * 10 + (hi - lo);
            if (key == col.v) continue;
            col.v = key;
            col.cap.style.top = (this.h - 2 - hi) + "px";
            col.cap.style.height = (hi - lo + 2) + "px";
            if (col.fill) {
                col.fill.style.top = (this.h - px) + "px";
                col.fill.style.height = px + "px";
            }
        }
    }
};

// ---- live zone ------------------------------------------------------------

// A Graph whose right quarter can be a live zone: past a thin white line it shows the last few
// seconds sampled every LIVE_MS, stretched, so short spikes and motion stay visible. The rest is
// the normal history. Without the live zone it is a plain Graph.
var LIVE_MS = 200;

function LiveGraph(parent, x, y, w, h, series, live) {
    var lw = live ? Math.round(w / 8) * 2 : 0;
    this.histW = lw ? w - lw - 1 : w;
    this.hist = new Graph(parent, x, y, this.histW, h, series);
    this.live = lw ? new Graph(parent, x + w - lw, y, lw, h, series) : null;
    if (lw) rect(parent, x + this.histW, y, 1, h, THEME.live);
}

LiveGraph.prototype.push = function (values) { this.hist.push(values); };

