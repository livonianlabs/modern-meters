// Sizes the gadget: a pre-rendered rounded panel (img/bg_<w>_<h>.png) on g:background gives the
// corners and border, and opaque divs of the panel color cover the interior. Text must sit on
// opaque HTML, otherwise the Sidebar blends its anti-aliasing with the magenta transparency key.
// Height is rounded up to the 10px steps the panels are generated in.
function paintFrame(w, h) {
    h = clamp(Math.ceil(h / 10) * 10, BG_MIN_H, BG_MAX_H);
    document.body.style.width = w + "px";
    document.body.style.height = h + "px";

    // Glass leaves a wider rim of the image uncovered for its glowing border
    var panel = $("panel"), r = THEME.glass ? 12 : 10, inset = THEME.glass ? 4 : 1;
    panel.innerHTML = "";
    if (!THEME.glass) {
        rect(panel, inset, r, w - 2 * inset, h - 2 * r, THEME.panel);
        rect(panel, r, inset, w - 2 * r, h - 2 * inset, THEME.panel);
    } else {
        // Same vertical gradient as the image: over the top GLASS_GRADIENT_H px, then flat, so
        // gadgets of any height have the same shade at the same distance from their top. Each
        // piece gets the colors at its own top and bottom.
        var at = function (y) { return mix(THEME.panelTop, THEME.panelBottom, Math.min(y / GLASS_GRADIENT_H, 1)); };
        var shade = function (x, y0, wd, y1) {
            var mid = Math.min(Math.max(y0, GLASS_GRADIENT_H), y1);
            if (mid > y0) gradient(rect(panel, x, y0, wd, mid - y0, THEME.panel), at(y0), at(mid));
            if (y1 > mid) rect(panel, x, mid, wd, y1 - mid, THEME.panelBottom);
        };
        shade(inset, r, w - 2 * inset, h - r);
        shade(r, inset, w - 2 * r, h - inset);
        // Gloss over the top, kept on the opaque pieces (over the bare corners it would blend
        // with the Sidebar's transparency color)
        var gloss = function (y) { return Math.round(clamp(1 - (y - inset) / 70, 0, 1) * 22); };
        var alpha = function (y) { var v = gloss(y); return "#" + (v < 16 ? "0" : "") + v.toString(16) + "FFFFFF"; };
        gradient(box(panel, r, inset, w - 2 * r, r - inset), alpha(inset), alpha(r));
        gradient(box(panel, inset, r, w - 2 * inset, 70 + inset - r), alpha(r), alpha(70 + inset));
        // CRT scanlines (img/scan.png, translucent), kept off the bare corners like the gloss
        if (THEME.terminal) {
            // Each piece offsets the pattern by its own top so the lines run on across them
            var scan = function (x, y, wd, ht) {
                box(panel, x, y, wd, ht, "background-image:url(img/scan.png);background-position:0 " + (-y) + "px;");
            };
            scan(r, inset, w - 2 * r, r - inset);
            scan(inset, r, w - 2 * inset, h - 2 * r);
            scan(r, h - r, w - 2 * r, r - inset);
        }
    }
    document.body.style.fontFamily = THEME.font || "'Segoe UI'";

    if (!IS_GADGET) {
        // Preview outside the Sidebar (e.g. mshta)
        document.body.style.backgroundColor = THEME.panel;
        try {
            var k = (screen.deviceXDPI || 96) / 96;
            document.body.scroll = "no";
            window.moveTo(0, 0);
            window.resizeTo(Math.round((w + 20) * k), Math.round((h + 50) * k));
        } catch (e) { }
        return;
    }
    var bg = $("bg"), file = w + "_" + h + ".png";
    // Panels in the theme's own colors are drawn on first use; the bundled navy glass stands in
    // if that fails
    var src = null;
    if (THEME.name == "classic") src = "img/bg_" + file;
    else if (THEME.name != "glass") src = themeImage(themeKey() + "_" + file, function (p, path) {
        return p.Glass(path, w, h, THEME.panelTop, THEME.panelBottom, GLASS_GRADIENT_H, THEME.edge, THEME.glow, THEME.gloss);
    });
    bg.src = src || "img/glass_" + file;
    bg.style.width = w + "px";
    bg.style.height = h + "px";
}

// Turns a label into a clickable hint, or back into plain text (action null). action is a web
// page to open or a function to run.
function setHint(el, tip, action) {
    if (el._action === action) return;
    el._action = action;
    el.title = action ? tip : "";
    el.style.cursor = action ? "hand" : "default";
    el.onclick = !action ? null : (typeof action == "function" ? action : function () { openUrl(action); });
}

// Registers a COM-visible .NET 4 class from <assembly>.dll in this gadget's folder for the
// current user (no admin needed), so new ActiveXObject(cls) works here and in helper scripts
function registerDotNet(clsid, cls, assembly) {
    var shell = new ActiveXObject("WScript.Shell");
    var keyCls = "HKCU\\Software\\Classes\\" + cls + "\\";
    var keyId = "HKCU\\Software\\Classes\\CLSID\\" + clsid + "\\";
    var inproc = keyId + "InprocServer32\\";
    shell.RegWrite(keyCls, cls, "REG_SZ");
    shell.RegWrite(keyCls + "CLSID\\", clsid, "REG_SZ");
    shell.RegWrite(keyId, cls, "REG_SZ");
    shell.RegWrite(keyId + "ProgId\\", cls, "REG_SZ");
    shell.RegWrite(inproc, "mscoree.dll", "REG_SZ");
    shell.RegWrite(inproc + "ThreadingModel", "Both", "REG_SZ");
    shell.RegWrite(inproc + "Class", cls, "REG_SZ");
    shell.RegWrite(inproc + "Assembly", assembly + ", Version=1.0.0.0, Culture=neutral, PublicKeyToken=null", "REG_SZ");
    shell.RegWrite(inproc + "RuntimeVersion", "v4.0.30319", "REG_SZ");
    shell.RegWrite(inproc + "CodeBase", "file:///" + System.Gadget.path.replace(/\\/g, "/") + "/" + assembly + ".dll", "REG_SZ");
}

