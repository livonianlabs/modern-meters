function T(key) {
    var s = (STRINGS[LANG] || STRINGS.en)[key];
    return s == null ? STRINGS.en[key] : s;
}

// "used / total unit"; narrow gadgets drop the spaces around the slash, unitKey null drops the unit
function fmtPair(a, b, unitKey, tight) {
    return a + (tight ? "/" : " / ") + b + (unitKey ? " " + T(unitKey) : "");
}

// ---- formatting -----------------------------------------------------------

function clamp(v, lo, hi) { return v < lo ? lo : (v > hi ? hi : v); }

function num(s) {
    var v = parseFloat(s);
    return isNaN(v) ? null : v;
}

function trim(s) { return String(s).replace(/^\s+|\s+$/g, ""); }

// Scales v by `base` until it is below 1000 and appends the matching unit (string keys).
// exact: no padding zeros (graph scale labels like "20 Mbit/s")
function scaled(v, units, base, exact) {
    var i = 0;
    while (v >= 1000 && i < units.length - 1) { v /= base; i++; }
    var s = exact ? String(parseFloat(v.toFixed(2))) :
        (i == 0 || v >= 100 ? v.toFixed(0) : (v >= 10 ? v.toFixed(1) : v.toFixed(2)));
    return s + " " + T(units[i]);
}

function fmtBytes(b) {
    return scaled(b, ["B", "KB", "MB", "GB", "TB"], 1024);
}

function fmtByteRate(b) {
    return scaled(b, ["Bs", "KBs", "MBs", "GBs"], 1024);
}

function fmtGB(bytes) {
    var gb = bytes / 1073741824;
    return gb >= 100 ? gb.toFixed(0) : gb.toFixed(1);
}

// Temperature in Celsius -> display string in the configured unit
function fmtTemp(c, unit) {
    if (c == null) return "–";
    return (unit == "F" ? Math.round(c * 9 / 5 + 32) : Math.round(c)) + "°";
}

// Five-step status scale: below normal, normal, above normal, loaded, overloaded
var LEVELS = ["#4cc2ff", "#7ee787", "#f5d547", "#ff9f43", "#ff5f56"];
var LOAD_STEPS = [25, 50, 75, 90];   // percent
var TEMP_STEPS = [45, 65, 78, 88];   // degrees Celsius

function levelIndex(v, steps) {
    for (var i = 0; i < steps.length; i++) if (v < steps[i]) return i;
    return steps.length;
}

function levelColor(v, steps) {
    return v == null ? THEME.faint : LEVELS[levelIndex(v, steps)];
}

function pctColor(pct) { return levelColor(pct, LOAD_STEPS); }

function tempColor(c) { return levelColor(c, TEMP_STEPS); }

// Bars keep the accent color and switch to the scale's orange/red only when loaded
function loadColor(pct, accent) {
    return pct >= LOAD_STEPS[2] ? pctColor(pct) : accent;
}

