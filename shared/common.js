function $(id) { return document.getElementById(id); }

function box(parent, x, y, w, h, css) {
    var d = document.createElement("div");
    d.style.cssText = "position:absolute;overflow:hidden;left:" + x + "px;top:" + y + "px;" +
        (w != null ? "width:" + w + "px;" : "") + (h != null ? "height:" + h + "px;" : "") + (css || "");
    parent.appendChild(d);
    return d;
}

// Small IE boxes grow to the font height unless font-size is forced down
function rect(parent, x, y, w, h, color) {
    return box(parent, x, y, w, h, "font-size:1px;line-height:1px;background-color:" + color + ";");
}

function label(parent, x, y, w, size, color, align, bold) {
    var d = box(parent, x, y, w, size + 6,
        "font-size:" + fontSize(size) + "px;line-height:" + (size + 6) + "px;white-space:nowrap;color:" + color +
        ";text-align:" + (align || "left") + ";" + fontCss(bold));
    return d;
}

// The terminal's monospace runs wider than Segoe UI, so its text is set a little smaller in the
// same boxes
