var flyoutHtml = "";

function esc(s) {
    return String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// sections: [{ title, rows: [[label, value], ...] }]; rows with an empty value are left out.
// In the gadget's colors and font: titles in its accent, the terminal's monospace.
function detailsHtml(sections) {
    var h = "", font = "font-family:" + (THEME.font || "'Segoe UI'") + ";font-size:" + fontSize(12) + "px;";
    var title = "style=\"color:" + ACCENTS[accentName()] + ";border-bottom-color:" + THEME.sep + ";" + font +
        (THEME.font ? "font-weight:bold;" : "font-family:'Segoe UI Semibold','Segoe UI';") + "\"";
    for (var i = 0; i < sections.length; i++) {
        var s = sections[i], body = "";
        for (var j = 0; j < s.rows.length; j++) {
            var v = s.rows[j][1];
            if (v == null || v === "") continue;
            body += "<tr><td class='k' style='color:" + THEME.dim + "'>" + esc(s.rows[j][0]) + "</td><td class='v'>" + esc(v) + "</td></tr>";
        }
        if (body) h += "<div class='t' " + title + ">" + esc(s.title) + "</div><table style=\"" + font + "color:" + THEME.text + "\">" + body + "</table>";
    }
    return h;
}

function flyoutPage(sections) {
    return "<div class='" + (THEME.light ? "light" : (THEME.glass ? "glass" : "classic")) + "' style='background-color:" + THEME.panel +
        (THEME.edge ? ";border-color:" + THEME.edge : "") + "'>" + detailsHtml(sections) + "</div>";
}

var flyoutTimer = null;

// A row naming the program that loads the processor (or the graphics card) most right now.
// Clicking it opens Task Manager.
var TOP_EVERY = 5000;

// x: start further right, on a line shared with something else, without the "Busiest:" (it is
// in the tooltip then)
function TopRow(root, y, x) {
    this.compact = x != null;
    x = x || PAD;
    var vw = this.compact ? 32 : 40;
    this.name = label(root, x, y, W - PAD - vw - x, this.compact ? 10 : 11, THEME.dim, this.compact ? "right" : "left");
    this.name.style.textOverflow = "ellipsis";
    this.val = label(root, W - PAD - vw, y, vw, this.compact ? 10 : 11, THEME.text, "right", true);
    this.name.style.cursor = this.val.style.cursor = "hand";
    this.name.title = this.val.title = T("topTip");
    this.name.onclick = this.val.onclick = function () { openUrl("taskmgr.exe"); };
    this.key = null;
    this.set(null, 0);
}

// name null: nothing busy (or not measured yet)
TopRow.prototype.set = function (name, pct) {
    var key = name + "|" + THEME.text;
    if (key != this.key) {
        this.key = key;
        this.name.innerHTML = (this.compact ? "" : esc(T("topProc")) + "&nbsp; ") +
            "<span style='color:" + THEME.text + "'>" + esc(name == null ? (this.compact ? "" : "–") : name) + "</span>";
    }
    setText(this.val, name == null ? "" : Math.round(pct) + "%");
    setColor(this.val, pctColor(pct));
};

// [label, value] rows of the TOP_N biggest of [{ name, n (processes), <key> }] by `key`; fmt
// formats a value and returns "" to leave the item out
var TOP_N = 6;

function topRows(list, key, fmt) {
    list.sort(function (a, b) { return b[key] - a[key]; });
    var rows = [];
    for (var i = 0; i < list.length && rows.length < TOP_N; i++) {
        var v = fmt(list[i][key]);
        if (v) rows.push([list[i].name + (list[i].n > 1 ? "  ×" + list[i].n : ""), v]);
    }
    return rows;
}

// Opens the details flyout beside the gadget, or closes it when it is already open.
// sections: an array, or a function returning one; with `every` (ms) the function runs again
// that often while the flyout stays open, and the flyout redraws.
function toggleDetails(sections, every) {
    if (!IS_GADGET) return;
    var f = System.Gadget.Flyout;
    if (flyoutTimer) clearInterval(flyoutTimer);
    flyoutTimer = null;
    if (f.show) { f.show = false; return; }
    var build = typeof sections == "function" ? sections : function () { return sections; };
    flyoutHtml = flyoutPage(build());
    f.file = "flyout.html";
    f.show = true;
    if (!every) return;
    flyoutTimer = setInterval(function () {
        if (!f.show) { clearInterval(flyoutTimer); flyoutTimer = null; return; }
        flyoutHtml = flyoutPage(build());
        try { f.document.parentWindow.render(flyoutHtml); } catch (e) { }
    }, every);
}

// "20261018054836.000000+180" -> "2026-10-18 05:48"
function cimDate(s) {
    var m = /^(\d{4})(\d\d)(\d\d)(\d\d)(\d\d)/.exec(String(s || ""));
    return m ? m[1] + "-" + m[2] + "-" + m[3] + " " + m[4] + ":" + m[5] : "";
}

// ---- update check ---------------------------------------------------------
// Once a day one of the gadgets asks GitHub for the latest release and writes the answer to
// %APPDATA%\ModernMeters\update.txt, where the others pick it up. A newer version shows a badge;
// only a click on it downloads the release and installs it (update.ps1).

var VERSION = "1.8.2";   // set by build.ps1
var REPO = "livonianlabs/modern-meters";
var KOFI_URL = "https://ko-fi.com/silverenio";
var MAKER = "Livonian Labs", MAIL = "livonianlabs@gmail.com";
var UPDATE_EVERY = 24 * 3600 * 1000;
var updates = { timer: null, req: null, sent: 0, shown: false, state: "", onChange: null, blink: null, root: null, badge: null };
var INSTALL_TIMEOUT = 5 * 60 * 1000;

// %APPDATA%\ModernMeters\<name>: key=value files the gadgets share
function sharedPath(name) {
    return new ActiveXObject("WScript.Shell").ExpandEnvironmentStrings("%APPDATA%") + "\\ModernMeters\\" + name;
}

function readUpdateFile() { return readShared("update.txt"); }

function writeUpdateFile(s) { writeShared("update.txt", s); }

function readShared(name) {
    var s = {};
    try {
        var f = new ActiveXObject("Scripting.FileSystemObject").OpenTextFile(sharedPath(name), 1), lines = f.ReadAll().split(/\r?\n/);
        f.Close();
        for (var i = 0; i < lines.length; i++) {
            var at = lines[i].indexOf("=");
            if (at > 0) s[lines[i].substring(0, at)] = lines[i].substring(at + 1);
        }
    } catch (e) { }
    return s;
}

// Written to a temporary file that then takes the name's place, so another gadget reading at the
// same moment never gets half a file
function writeShared(name, s) {
    try {
        var fso = new ActiveXObject("Scripting.FileSystemObject"), path = sharedPath(name), dir = fso.GetParentFolderName(path);
        if (!fso.FolderExists(dir)) fso.CreateFolder(dir);
        var tmp = path + "." + Math.floor(Math.random() * 1e9) + ".tmp", f = fso.CreateTextFile(tmp, true), text = "";
        for (var k in s) text += k + "=" + s[k] + "\r\n";
        f.Write(text);
        f.Close();
        if (fso.FileExists(path)) fso.DeleteFile(path, true);
        fso.MoveFile(tmp, path);
    } catch (e) { }
}

// "v1.2.0" > "1.1.9"
function isNewer(a, b) {
    var pa = String(a).replace(/^v/i, "").split("."), pb = String(b).replace(/^v/i, "").split(".");
    for (var i = 0; i < 3; i++) {
        var x = parseInt(pa[i], 10) || 0, y = parseInt(pb[i], 10) || 0;
        if (x != y) return x > y;
    }
    return false;
}

// The newer release as { latest, url }, or null
function updateAvailable() {
    if (getSetting("updates") == "off") return null;
    var s = readUpdateFile();
    return s.latest && isNewer(s.latest, VERSION) ? s : null;
}

// "↑ x.y.z" while a newer release exists, in a corner that is free in every gadget, so the
// gadget keeps its height and doesn't run into its neighbors: the right end of the title bar in
// glass, the top margin in classic. Call it after the content so it is drawn on top.
// A click installs it; until then it blinks in step with the terminal cursor. "↻ x.y.z" while
// that runs. After a failed install the click opens the release page instead.
function updateBadge(root) {
    if (updates.blink) clearInterval(updates.blink);
    updates.blink = null;
    updates.root = root;
    updates.badge = null;
    var s = updateAvailable();
    updates.shown = !!s;
    updates.state = s ? installState(s.latest).state : "";
    if (!s) return;
    var ver = s.latest.replace(/^v/i, ""), page = s.url || "https://github.com/" + REPO + "/releases/latest";
    var c = THEME.titleBar ? "#ffffff" : ACCENTS[accentName()];
    var l = THEME.glass ? label(root, W - PAD - 40, 10, 40, 9, c, "right", true) :
        label(root, W - PAD - 40, -1, 40, 8, c, "right", true);
    // Done counts as running until the gadget reloads into the new version
    var st = installState(s.latest), busy = st.state == "running" || st.state == "done";
    var head = T("update").replace("%s", ver).replace(" ›", "") + ". ";
    setText(l, (busy ? "↻ " : "↑ ") + ver);
    if (busy) setHint(l, head + T("updating"), function () { });
    else if (st.state == "failed") setHint(l, head + T("updateFailed").replace("%s", st.error || "?"), page);
    else setHint(l, head + T("updateHint"), function () { installUpdate(s.latest); });
    updates.badge = l;
    if (busy) return;
    // Not under the mouse: restyling it would take its tip away
    var on = true, hover = false, dim = THEME.titleBar ? THEME.titleBar[1] : THEME.faint;
    l.onmouseenter = function () { hover = true; setColor(l, c); };
    l.onmouseleave = function () { hover = false; };
    updates.blink = setInterval(function () {
        on = !on;
        if (!hover) setColor(l, on ? c : dim);
    }, 530);
}

// Redraws just the badge, for a change of the install state
function redrawBadge() {
    if (!updates.badge || !updates.root) return false;
    updates.badge.parentNode.removeChild(updates.badge);
    updateBadge(updates.root);
    return true;
}

// The install of release `tag` as { state: ""|running|failed|done, error }
function installState(tag) {
    var s = readShared("updating.txt");
    if (s.tag != tag) return { state: "" };
    if (!(new Date().getTime() - parseFloat(s.at) < INSTALL_TIMEOUT)) {
        // A run that went quiet failed; a done one that didn't bring this gadget the new version
        // (it lives in another folder) may be tried again
        if (s.state == "running") return { state: "failed", error: "timeout" };
        if (s.state == "done") return { state: "" };
    }
    return s;
}

// Runs update.ps1 hidden for every Modern Meters gadget next to this one. It writes its
// progress to updating.txt; the gadgets reload once it replaced their common.js.
function installUpdate(tag) {
    if (installState(tag).state == "running") return;
    writeShared("updating.txt", { state: "running", tag: tag, at: new Date().getTime() });
    try {
        var folder = new ActiveXObject("Scripting.FileSystemObject").GetParentFolderName(System.Gadget.path);
        new ActiveXObject("WScript.Shell").Run("powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File \"" +
            System.Gadget.path + "\\update.ps1\" -Tag \"" + tag + "\" -Folder \"" + folder + "\"", 0, false);
    } catch (e) {
        writeShared("updating.txt", { state: "failed", tag: tag, at: new Date().getTime(), error: e.message || "powershell" });
    }
    redrawBadge();
}

// ---- one style for all gadgets --------------------------------------------
// With "Apply to all gadgets" on, OK in a gadget's settings writes its style to
// %APPDATA%\ModernMeters\style.txt, and every gadget (also one added later) takes it over within
// STYLE_POLL ms. Width, graph and the rest stay per gadget.

var STYLE_POLL = 3000;
var SYNC_KEYS = { style: ["theme", "lang", "frost", "glass"], all: ["theme", "lang", "accent", "frost", "glass"] };

function syncMode(v) {
    return SYNC_KEYS[v] ? v : "off";
}

// Called by the settings page once it saved the form. Turning the option off is passed on too,
// so the gadgets stop following each other.
function shareStyle(wasMode) {
    var mode = syncMode(getSetting("sync"));
    if (mode == "off" && wasMode == "off") return;
    var s = { stamp: new Date().getTime(), sync: mode }, keys = SYNC_KEYS[mode] || [];
    for (var i = 0; i < keys.length; i++) s[keys[i]] = getSetting(keys[i]);
    writeShared("style.txt", s);
    setSetting("styleStamp", s.stamp);
}

// Takes over a style shared since this gadget last looked; true when anything changed
function adoptStyle() {
    var s = readShared("style.txt"), mine = parseFloat(getSetting("styleStamp")) || 0, stamp = parseFloat(s.stamp);
    // A newer style, or the current one not (fully) taken over yet
    if (!(stamp >= mine) || (stamp == mine && s.sync == "off")) return false;
    // Only a whole file (older versions wrote theme and lang too, not the newer keys): read again
    // next round otherwise
    if (s.sync != "off" && (s.theme == null || s.lang == null)) return false;
    var changed = false;
    for (var k in s) {
        if (k == "stamp" || getSetting(k) == s[k]) continue;
        setSetting(k, s[k]);
        changed = true;
    }
    // Marked as taken over only once every value is in
    if (stamp > mine) setSetting("styleStamp", s.stamp);
    return changed;
}

// Checks once a minute whether the daily request is due; onChange (the gadget's rebuild) runs
// when the update badge has to appear or go away, or the auto theme has to switch
function watchUpdates(onChange) {
    if (!IS_GADGET || updates.timer) return;
    updates.onChange = onChange;
    var poll = function () {
        var t = new Date().getTime(), s;
        if (updates.req) {
            if (updates.req.readyState != 4) {
                if (t - updates.sent > 60000) { try { updates.req.abort(); } catch (e) { } updates.req = null; }
                return;
            }
            var r = updates.req;
            updates.req = null;
            try {
                if (r.status == 200) {
                    var tag = /"tag_name"\s*:\s*"([^"]+)"/.exec(r.responseText);
                    var url = /"html_url"\s*:\s*"([^"]+)"/.exec(r.responseText);
                    if (tag) {
                        s = readUpdateFile();
                        s.latest = tag[1];
                        s.url = url ? url[1] : "";
                        writeUpdateFile(s);
                    }
                }
            } catch (e2) { }
        } else if (getSetting("updates") != "off") {
            s = readUpdateFile();
            if (!(t - parseFloat(s.checked) < UPDATE_EVERY)) {
                // Claimed before sending so the other gadgets skip this round
                s.checked = t;
                writeUpdateFile(s);
                try {
                    var req = new ActiveXObject("MSXML2.ServerXMLHTTP.6.0");
                    req.open("GET", "https://api.github.com/repos/" + REPO + "/releases/latest", true);
                    req.setRequestHeader("User-Agent", "ModernMeters/" + VERSION);
                    req.setRequestHeader("Accept", "application/vnd.github+json");
                    req.send();
                    updates.req = req;
                    updates.sent = t;
                } catch (e3) { }
                return;
            }
        }
        if (!!updateAvailable() != updates.shown) onChange();
    };
    updates.timer = setInterval(poll, 60000);
    setTimeout(poll, 10000);
    // Before the gadget's first build, so it starts in the shared style
    adoptStyle();
    setInterval(function () {
        // A new version was installed over this one (by a badge click or by hand)
        if (codeSettled()) { location.reload(); return; }
        var s = updateAvailable(), st = s ? installState(s.latest).state : "";
        if (adoptStyle()) onChange();
        else if (st != updates.state && !redrawBadge()) onChange();
    }, STYLE_POLL);
    // The auto theme follows Windows switching between light and dark mode
    setInterval(function () {
        if (getSetting("theme") == "auto" && themeName("auto") != THEME.name) onChange();
    }, 15000);
}

var LOADED_AT = new Date().getTime();

// True when a newer version was installed over the running gadget. The settings dialog is read
// from disk each time and may offer options this page's older code doesn't know.
function codeChanged() {
    return codeAge() >= 0;
}

// codeChanged, and nothing written for a few seconds, so a copy in progress is over
function codeSettled() {
    return codeAge() > 5000;
}

// How long ago common.js was replaced, or -1 when it is the one this page loaded
function codeAge() {
    try {
        var f = new ActiveXObject("Scripting.FileSystemObject").GetFile(System.Gadget.path + "\\common.js");
        var t = new Date(f.DateLastModified).getTime();
        return t > LOADED_AT ? new Date().getTime() - t : -1;
    } catch (e) {
        return -1;
    }
}

function hookSettings(onCommit) {
    if (!IS_GADGET) return;
    System.Gadget.settingsUI = "settings.html";
    System.Gadget.onSettingsClosed = function (e) {
        if (e.closeAction != e.Action.commit) return;
        if (codeChanged()) location.reload();
        else onCommit();
    };
}
