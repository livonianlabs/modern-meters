var soundPlayer = null;

// Plays a sound from %WINDIR%\Media; volume 0..100
function playSound(file, volume) {
    try {
        if (!soundPlayer) soundPlayer = new ActiveXObject("WMPlayer.OCX");
        soundPlayer.settings.volume = volume;
        soundPlayer.URL = new ActiveXObject("WScript.Shell").ExpandEnvironmentStrings("%WINDIR%") + "\\Media\\" + file;
        soundPlayer.controls.play();
    } catch (e) { }
}

function stopSound() {
    try { if (soundPlayer) soundPlayer.controls.stop(); } catch (e) { }
}

function soundBusy() {
    try {
        var s = soundPlayer ? soundPlayer.playState : 0;
        return s == 3 || s == 6 || s == 9 || s == 11;   // playing, buffering, transitioning, reconnecting
    } catch (e) {
        return false;
    }
}

// The ♪ icon: grey when off, light when armed, blinking red while the value is over the limit.
// Clicking it while alarming silences it until the value drops `hyst` below the limit;
// otherwise it turns the alarm on or off.
// opts (optional): { limit, hyst, tips: {on, off, stop} string keys, onClear: called when an
// alarm that went off is over }. By default it watches a temperature against "alarmTemp".
function Alarm(parent, x, y, opts) {
    var self = this;
    opts = opts || {};
    this.icon = label(parent, x, y - 2, 14, 13, THEME.faint, "center");
    setText(this.icon, "♪");
    this.icon.style.cursor = "hand";
    this.icon.onclick = function () { self.click(); };
    this.on = getSetting("alarm") == "on";
    this.limit = opts.limit != null ? opts.limit : parseFloat(getSetting("alarmTemp"));
    this.hyst = opts.hyst != null ? opts.hyst : 3;
    this.tips = opts.tips || { on: "alarmOn", off: "alarmOff", stop: "alarmStop" };
    this.onClear = opts.onClear;
    this.firing = false;
    this.snoozed = false;
    this.blink = false;
    this.paint();
}

Alarm.prototype.update = function (value) {
    this.icon.style.display = value == null ? "none" : "";
    if (this.on && value != null && value >= this.limit) {
        if (!this.firing && !this.snoozed) {
            this.firing = true;
            this.play();
        } else if (this.firing && getSetting("repeat") == "loop" && !soundBusy()) {
            this.play();
        }
    } else if (value == null || value < this.limit - this.hyst) {
        var wentOff = this.firing || this.snoozed;
        if (this.firing) stopSound();
        this.firing = false;
        this.snoozed = false;
        if (wentOff && this.onClear && value != null) this.onClear();
    }
    this.blink = !this.blink;
    this.paint();
};

Alarm.prototype.play = function () {
    playSound(getSetting("sound"), parseInt(getSetting("volume"), 10));
};

Alarm.prototype.click = function () {
    if (this.firing) {
        stopSound();
        this.firing = false;
        this.snoozed = true;
    } else {
        this.on = !this.on;
        setSetting("alarm", this.on ? "on" : "off");
    }
    this.paint();
};

Alarm.prototype.paint = function () {
    setColor(this.icon, this.firing ? (this.blink ? THEME.hot : LEVELS[3]) : (this.on ? THEME.dim : THEME.faint));
    this.icon.title = T(this.firing ? this.tips.stop : (this.on ? this.tips.on : this.tips.off));
};

Alarm.prototype.dispose = function () {
    if (this.firing) stopSound();
};

// ---- details flyout -------------------------------------------------------

// The flyout page (flyout.html) pulls this when it opens
var flyoutHtml = "";

function esc(s) {
    return String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// sections: [{ title, rows: [[label, value], ...] }]; rows with an empty value are left out
function detailsHtml(sections) {
    var h = "";
    for (var i = 0; i < sections.length; i++) {
        var s = sections[i], body = "";
        for (var j = 0; j < s.rows.length; j++) {
            var v = s.rows[j][1];
            if (v == null || v === "") continue;
            body += "<tr><td class='k'>" + esc(s.rows[j][0]) + "</td><td class='v'>" + esc(v) + "</td></tr>";
        }
        if (body) h += "<div class='t'>" + esc(s.title) + "</div><table>" + body + "</table>";
    }
    return h;
}

// Opens the details flyout beside the gadget, or closes it when it is already open
function toggleDetails(sections) {
    if (!IS_GADGET) return;
    var f = System.Gadget.Flyout;
    if (f.show) { f.show = false; return; }
    flyoutHtml = "<div class='" + (THEME.glass ? "glass" : "classic") + "'>" + detailsHtml(sections) + "</div>";
    f.file = "flyout.html";
    f.show = true;
}

// "20261018054836.000000+180" -> "2026-10-18 05:48"
function cimDate(s) {
    var m = /^(\d{4})(\d\d)(\d\d)(\d\d)(\d\d)/.exec(String(s || ""));
    return m ? m[1] + "-" + m[2] + "-" + m[3] + " " + m[4] + ":" + m[5] : "";
}

// ---- update check ---------------------------------------------------------
// Once a day one of the gadgets asks GitHub for the latest release and writes the answer to
// %APPDATA%\ModernMeters\update.txt, where the others pick it up. A newer version only shows a
// line linking to its release page; nothing is downloaded.

var VERSION = "1.0.0";   // set by build.ps1
var REPO = "Silverenio/modern-meters";
var KOFI_URL = "https://ko-fi.com/silverenio";
var UPDATE_EVERY = 24 * 3600 * 1000;
var updates = { timer: null, req: null, sent: 0, shown: false };

function updatePath() {
    return new ActiveXObject("WScript.Shell").ExpandEnvironmentStrings("%APPDATA%") + "\\ModernMeters\\update.txt";
}

function readUpdateFile() {
    var s = {};
    try {
        var f = new ActiveXObject("Scripting.FileSystemObject").OpenTextFile(updatePath(), 1), lines = f.ReadAll().split(/\r?\n/);
        f.Close();
        for (var i = 0; i < lines.length; i++) {
            var at = lines[i].indexOf("=");
            if (at > 0) s[lines[i].substring(0, at)] = lines[i].substring(at + 1);
        }
    } catch (e) { }
    return s;
}

function writeUpdateFile(s) {
    try {
        var fso = new ActiveXObject("Scripting.FileSystemObject"), dir = fso.GetParentFolderName(updatePath());
        if (!fso.FolderExists(dir)) fso.CreateFolder(dir);
        var f = fso.CreateTextFile(updatePath(), true), text = "";
        for (var k in s) text += k + "=" + s[k] + "\r\n";
        f.Write(text);
        f.Close();
    } catch (e) { }
}

// "v1.2.0" > "1.1.9"
function isNewer(a, b) {
    var pa = String(a).replace(/^v/i, "").split("."), pb = String(b).replace(/^v/i, "").split(".");
    for (var i = 0; i < 3; i++) {
        var x = parseInt(pa[i], 10) || 0, y = parseInt(pb[i], 10) || 0;
        if (x != y) return x > y;
    }
    return false;
}

// The newer release as { latest, url }, or null
function updateAvailable() {
    if (getSetting("updates") == "off") return null;
    var s = readUpdateFile();
    return s.latest && isNewer(s.latest, VERSION) ? s : null;
}

// "New version x.y.z ›" under the content while a newer release exists; returns the y below it
function updateRow(root, y) {
    var s = updateAvailable();
    updates.shown = !!s;
    if (!s) return y;
    var l = label(root, PAD, y, W - 2 * PAD, 10, ACCENTS[accentName()], "center", true);
    setText(l, T("update").replace("%s", s.latest.replace(/^v/i, "")));
    setHint(l, T("updateHint"), s.url || "https://github.com/" + REPO + "/releases/latest");
    return y + 16;
}

// Checks once a minute whether the daily request is due; onChange (the gadget's rebuild) runs
// when the update line has to appear or go away
function watchUpdates(onChange) {
    if (!IS_GADGET || updates.timer) return;
    var poll = function () {
        var t = new Date().getTime(), s;
        if (updates.req) {
            if (updates.req.readyState != 4) {
                if (t - updates.sent > 60000) { try { updates.req.abort(); } catch (e) { } updates.req = null; }
                return;
            }
            var r = updates.req;
            updates.req = null;
            try {
                if (r.status == 200) {
                    var tag = /"tag_name"\s*:\s*"([^"]+)"/.exec(r.responseText);
                    var url = /"html_url"\s*:\s*"([^"]+)"/.exec(r.responseText);
                    if (tag) {
                        s = readUpdateFile();
                        s.latest = tag[1];
                        s.url = url ? url[1] : "";
                        writeUpdateFile(s);
                    }
                }
            } catch (e2) { }
        } else if (getSetting("updates") != "off") {
            s = readUpdateFile();
            if (!(t - parseFloat(s.checked) < UPDATE_EVERY)) {
                // Claimed before sending so the other gadgets skip this round
                s.checked = t;
                writeUpdateFile(s);
                try {
                    var req = new ActiveXObject("MSXML2.ServerXMLHTTP.6.0");
                    req.open("GET", "https://api.github.com/repos/" + REPO + "/releases/latest", true);
                    req.setRequestHeader("User-Agent", "ModernMeters/" + VERSION);
                    req.setRequestHeader("Accept", "application/vnd.github+json");
                    req.send();
                    updates.req = req;
                    updates.sent = t;
                } catch (e3) { }
                return;
            }
        }
        if (!!updateAvailable() != updates.shown) onChange();
    };
    updates.timer = setInterval(poll, 60000);
    setTimeout(poll, 10000);
}

function hookSettings(onCommit) {
    if (!IS_GADGET) return;
    System.Gadget.settingsUI = "settings.html";
    System.Gadget.onSettingsClosed = function (e) {
        if (e.closeAction == e.Action.commit) onCommit();
    };
}
